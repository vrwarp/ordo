import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { describe, expect, it } from 'vitest';

/**
 * `tools/download_golden_pptx.py`, which rewrites golden-pptx/manifest.json and README.md from its download
 * list, keeps the decks this repository generates (an entry with `generator` instead of `source_url`), and
 * the committed README is what it writes from the committed manifest. Run with `python3 -I` on a scratch copy
 * of golden-pptx's two files (`-B`: no bytecode written next to the script); skipped where there is no python3.
 */
const root = resolve(import.meta.dirname, '../../../..');
const script = join(root, 'tools/download_golden_pptx.py');
const python = spawnSync('python3', ['-I', '-c', 'print(1)'], { timeout: 10_000 }).status === 0;

/** Runs `body` (Python) with the script loaded as `dl` and its golden directory set to `dir`. */
function py(dir: string, body: string): { status: number | null; out: string; err: string } {
  const prelude = [
    'import importlib.util, json, os, sys, zipfile',
    `spec = importlib.util.spec_from_file_location('dl', ${JSON.stringify(script)})`,
    'dl = importlib.util.module_from_spec(spec); spec.loader.exec_module(dl)',
    `dl.GOLDEN_DIR = ${JSON.stringify(dir)}`,
  ].join('\n');
  const r = spawnSync('python3', ['-I', '-B', '-c', `${prelude}\n${body}`], {
    timeout: 60_000,
    encoding: 'utf8',
  });
  return { status: r.status, out: r.stdout, err: r.stderr };
}

describe.skipIf(!python)('download_golden_pptx.py and generated decks', () => {
  it('writes the committed README from the committed manifest (nothing downloaded)', () => {
    const dir = mkdtempSync(join(process.env.TMPDIR ?? tmpdir(), 'ordo-golden-'));
    try {
      const manifest = join(root, 'golden-pptx/manifest.json');
      const r = py(dir, `dl.generate_readme(json.load(open(${JSON.stringify(manifest)}, encoding='utf-8')))`);
      expect(r.err).toBe('');
      expect(readFileSync(join(dir, 'README.md'), 'utf8')).toBe(
        readFileSync(join(root, 'golden-pptx/README.md'), 'utf8'),
      );
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it('keeps a generated entry when it rewrites the manifest, refreshed from its file, and lists it in the README', () => {
    const dir = mkdtempSync(join(process.env.TMPDIR ?? tmpdir(), 'ordo-golden-'));
    try {
      const r = py(
        dir,
        [
          "os.makedirs(os.path.join(dl.GOLDEN_DIR, 'gen'))",
          "with zipfile.ZipFile(os.path.join(dl.GOLDEN_DIR, 'gen', 'made.pptx'), 'w') as z:",
          "    z.writestr('ppt/presentation.xml', '<p:presentation/>')",
          "    z.writestr('ppt/slides/slide1.xml', '<p:sld><a:custGeom/></p:sld>')",
          "    z.writestr('ppt/slides/slide2.xml', '<p:sld/>')",
          'downloaded = {"slide_count": 1, "master_count": 1, "features": [], "file_size_bytes": 10,',
          '  "rel_path": "x/a.pptx", "category": "x", "source_url": "https://example.org/a.pptx", "description": "A"}',
          'made = {"slide_count": 9, "features": [], "file_size_bytes": 1, "rel_path": "gen/made.pptx",',
          '  "category": "challenging-features", "generator": "tools/gen/made.ts", "description": "Made here"}',
          'dl.write_manifest([downloaded, made])',
          // A download run rewrites the manifest from its list (here: the downloaded entry alone).
          'merged = dl.merge_generated([downloaded], dl.read_manifest())',
          'print(json.dumps(merged))',
          'dl.generate_readme(merged)',
          // --readme: no download, the generated entries refreshed.
          "sys.argv = ['download_golden_pptx.py', '--readme']",
          'dl.main()',
        ].join('\n'),
      );
      expect(r.status, r.err).toBe(0);
      const merged = JSON.parse(r.out.split('\n').find((l) => l.startsWith('['))!) as Record<
        string,
        unknown
      >[];
      expect(merged.map((e) => e.rel_path)).toEqual(['x/a.pptx', 'gen/made.pptx']);
      expect(merged[1]).toMatchObject({
        slide_count: 2,
        features: ['customGeom'],
        generator: 'tools/gen/made.ts',
        description: 'Made here',
      });
      expect(merged[1]).not.toHaveProperty('source_url');
      const readme = readFileSync(join(dir, 'README.md'), 'utf8');
      expect(readme).toContain('| [`made.pptx`](gen/made.pptx) | challenging-features | 2 | ');
      expect(readme).toContain('generated by [`made.ts`](../tools/gen/made.ts) | Made here |');
      expect(readme).toContain('[a.pptx](https://example.org/a.pptx) | A |');
      const manifest = JSON.parse(readFileSync(join(dir, 'manifest.json'), 'utf8')) as Record<
        string,
        unknown
      >[];
      expect(manifest.map((e) => [e.rel_path, e.slide_count])).toEqual([
        ['x/a.pptx', 1],
        ['gen/made.pptx', 2],
      ]);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});
